#!/bin/bash
# Run only against live-build's finished payload, outside its mount namespace.
set -euo pipefail
target=${1:?expected live-build payload root}
[[ $target == /build/node/build/chroot/chroot && -d $target/usr/lib/bitcoin-core-node && ! -L $target ]]
sources=$target/etc/apt/sources.list.d
mv "$sources/core-node.sources.runtime" "$sources/core-node.sources"
# The installed Node already has both ordinary and security mirrors in its
# managed deb822 source. Discard live-build's temporary duplicate and snapshot.
rm -f "$target/etc/apt/sources.list" "$sources/debian.sources"
if grep -rE 'snapshot\.debian\.org|Check-Valid-Until' "$target/etc/apt" --exclude-dir=trusted.gpg.d; then
    echo 'A build-only APT setting would escape into the installed Node.' >&2
    exit 1
fi

# These caches are generated by package/configuration scripts at build time.
# Rebuildable caches and machine-specific entropy do not belong to a master.
rm -f "$target/var/cache/ldconfig/aux-cache" "$target/var/lib/systemd/random-seed"
find "$target/var/log" -type f -exec truncate -s 0 {} +
find "$target/usr" -type f -name '*.pyc' -delete
# Locked system accounts have no interactive password to age. Stabilise
# the creation-day field only for those accounts in this freshly built image.
python3 - "$target" <<'PY'
import os
from pathlib import Path
import sys
root = Path(sys.argv[1])
for name in ('shadow', 'shadow-'):
    path = root / 'etc' / name
    if path.is_file():
        rows = []
        for line in path.read_text().splitlines():
            row = line.split(':')
            if len(row) == 9 and row[1].startswith(('!', '*')) and row[2].isdigit():
                row[2] = str(int(os.environ['SOURCE_DATE_EPOCH']) // 86400)
            rows.append(':'.join(row))
        path.write_text('\n'.join(rows) + '\n')
PY
# Keep sidecar data outside the ISO so a discrepancy can be localized even
# if an offline builder chooses to share only these hashes.
(cd "$target" && find . -xdev -type f -print0 | LC_ALL=C sort -z | xargs -0r sha256sum) \
    | gzip -n > /out/root-files.sha256.gz
